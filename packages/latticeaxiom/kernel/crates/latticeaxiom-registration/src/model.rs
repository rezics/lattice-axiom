/// Numeric layout and schedule receipt used by the activation gate.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct RegistrationImageReceipt {
    /// Receipt schema version.
    pub schema_version: u32,
    /// Frozen graph semantic hash.
    pub graph_hash: CanonicalHash,
    /// Closure-wide semantic contract hash, excluding provenance.
    pub registration_semantic_hash: CanonicalHash,
    /// Exact legacy registration image hash.
    pub image_hash: CanonicalHash,
    /// Per-kind dense numeric layouts.
    pub numeric_ids: BTreeMap<RegistrationKind, BTreeMap<StableId, NumericRegistrationId>>,
    /// Deterministic schedule after stage and edge compilation.
    pub schedule: Vec<StableId>,
    /// Content address of all preceding fields.
    pub receipt_hash: CanonicalHash,
}

impl RegistrationImageReceipt {
    /// Recomputes this receipt's content address.
    ///
    /// # Errors
    ///
    /// Returns [`CanonicalJsonError`] if canonical JSON encoding fails.
    pub fn recompute_hash(&self) -> Result<CanonicalHash, CanonicalJsonError> {
        canonical_json_hash(&ImageReceiptIdentity::from(self))
    }

    /// Verifies the receipt hash and dense per-kind numeric layout.
    ///
    /// # Errors
    ///
    /// Returns [`ReceiptValidationError`] for an unsupported schema, a hash
    /// mismatch, or a gap/reordering in any numeric table.
    pub fn verify(&self) -> Result<(), ReceiptValidationError> {
        verify_schema(self.schema_version)?;
        for (kind, table) in &self.numeric_ids {
            for (expected, (stable, actual)) in table.iter().enumerate() {
                if stable.kind() != registration_kind_name(*kind) {
                    return Err(ReceiptValidationError::NumericKindMismatch {
                        kind: *kind,
                        stable: stable.clone(),
                    });
                }
                let expected = u32::try_from(expected)
                    .map_err(|_| ReceiptValidationError::NumericTableTooLarge { kind: *kind })?;
                if actual.0 != expected {
                    return Err(ReceiptValidationError::NonDenseNumericIds {
                        kind: *kind,
                        stable: stable.clone(),
                        expected,
                        actual: actual.0,
                    });
                }
            }
        }
        verify_hash(self.receipt_hash, self.recompute_hash()?)
    }
}

