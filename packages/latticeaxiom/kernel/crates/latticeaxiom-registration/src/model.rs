/// Structured, stable semantic resolution evidence.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields, rename_all = "kebab-case", tag = "step")]
pub enum SemanticResolutionStep {
    /// Deterministic candidates considered for one Role.
    Candidates {
        /// Role being resolved.
        role: StableId,
        /// Sorted candidate targets.
        targets: Vec<StableId>,
    },
    /// One required Role had no candidate before the fallback wave.
    Missing {
        /// Role deferred to fallback selection.
        role: StableId,
    },
    /// One atomic fallback bundle became active.
    FallbackActivated {
        /// Activated bundle ID.
        bundle: StableId,
        /// Missing Roles authorizing activation.
        roles: Vec<StableId>,
    },
    /// Final binding selected for one Role.
    Bound {
        /// Role being resolved.
        role: StableId,
        /// Sorted selected targets.
        targets: Vec<StableId>,
        /// Selection rule.
        selected_by: RoleSelectionRule,
    },
}

