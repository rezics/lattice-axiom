/// Callback map independently verified before any package code executes.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct CallbackMapReceipt {
    /// Receipt schema version.
    pub schema_version: u32,
    /// Frozen graph semantic hash.
    pub graph_hash: CanonicalHash,
    /// Closure-wide semantic contract hash shared by every compiler receipt.
    pub registration_semantic_hash: CanonicalHash,
    /// Callback bindings keyed by stable callback key.
    pub callbacks: BTreeMap<StableId, CallbackBinding>,
    /// Scheduled systems independently projected to callback key and signature.
    pub systems: BTreeMap<StableId, SystemCallbackProjection>,
    /// Content address of all preceding fields.
    pub callback_map_hash: CanonicalHash,
}

impl CallbackMapReceipt {
    /// Recomputes the callback-map hash.
    ///
    /// # Errors
    ///
    /// Returns [`CanonicalJsonError`] if canonical JSON encoding fails.
    pub fn recompute_hash(&self) -> Result<CanonicalHash, CanonicalJsonError> {
        canonical_json_hash(&CallbackReceiptIdentity::from(self))
    }

    /// Verifies schema and callback-map hash.
    ///
    /// # Errors
    ///
    /// Returns [`ReceiptValidationError`] for an unsupported schema or mismatch.
    pub fn verify(&self) -> Result<(), ReceiptValidationError> {
        verify_schema(self.schema_version)?;
        for (system, projection) in &self.systems {
            let Some(callback) = self.callbacks.get(&projection.callback) else {
                return Err(ReceiptValidationError::SystemCallbackProjectionMismatch {
                    system: system.clone(),
                });
            };
            if system.kind() != "system"
                || callback.signature_hash != projection.signature_hash
                || !callback.consumers.contains(system)
            {
                return Err(ReceiptValidationError::SystemCallbackProjectionMismatch {
                    system: system.clone(),
                });
            }
        }
        for (callback, binding) in &self.callbacks {
            for consumer in binding
                .consumers
                .iter()
                .filter(|consumer| consumer.kind() == "system")
            {
                let Some(projection) = self.systems.get(consumer) else {
                    return Err(ReceiptValidationError::SystemCallbackProjectionMismatch {
                        system: consumer.clone(),
                    });
                };
                if &projection.callback != callback
                    || projection.signature_hash != binding.signature_hash
                {
                    return Err(ReceiptValidationError::SystemCallbackProjectionMismatch {
                        system: consumer.clone(),
                    });
                }
            }
        }
        verify_hash(self.callback_map_hash, self.recompute_hash()?)
    }
}

