/// Deterministic reason selecting one Role binding.
#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum RoleSelectionRule {
    /// A single normal candidate satisfied the contract.
    Unique,
    /// The frozen composition profile selected the target.
    Profile,
    /// A single fallback wave supplied the target.
    Fallback,
}

